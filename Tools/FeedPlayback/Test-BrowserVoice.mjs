import fs from 'node:fs';
import path from 'node:path';import vm from 'node:vm';import assert from 'node:assert/strict';
const projectRoot=process.argv[3]||process.cwd();
const source=fs.readFileSync(path.join(projectRoot,'Assets/Plugins/WebGL/FeedPlaybackAudio.jslib'),'utf8');
const ctx={LibraryManager:{library:{}},WEBAudio:{audioInstances:{},FAKEMOD_SAMPLERATE:44100,audioContext:{currentTime:0,state:'suspended'}},mergeInto:(a,b)=>Object.assign(a,b)};
vm.createContext(ctx);vm.runInContext(source,ctx);const api=ctx.LibraryManager.library;ctx.FeedVoiceState=api.$FeedVoiceState;

const checks=[];const test=(name,fn)=>{fn();checks.push({name,passed:true});};
const makeMedia=()=>{const listeners=new Set();return {currentTime:0,paused:false,ended:false,onPlay:f=>listeners.add(f),offPlay:f=>listeners.delete(f),emit:()=>[...listeners].forEach(f=>f()),listeners};};
const media=makeMedia();const clip={getLength:()=>11*44100,createSourceNode:()=>({mediaElement:media,isStopped:false})};
ctx.WEBAudio.audioInstances[1]={getLength:()=>70*44100,createSourceNode:()=>({})};
api.FeedVoice_Remember();ctx.WEBAudio.audioInstances[2]=clip;
test('绑定只识别新加载的精确配音Clip',()=>assert.equal(api.FeedVoice_Bind(11),1));
const original=ctx.FeedVoiceState.original;const node=clip.createSourceNode();
test('声道已创建未onPlay保持冻结',()=>assert.equal(api.FeedVoice_Position(),-1));
api.FeedVoice_Arm();test('Arm不伪造实际起播',()=>assert.equal(api.FeedVoice_Position(),-1));
media.emit();test('目标onPlay确认后允许零头',()=>assert.equal(api.FeedVoice_Position(),0));
media.currentTime=4.2;test('优先真实宿主播放头',()=>assert.equal(api.FeedVoice_Position(),4.2));
media.paused=true;test('隐藏暂停不推进',()=>assert.equal(api.FeedVoice_Position(),-1));
media.paused=false;const late=ctx.FeedVoiceState.onPlay;api.FeedVoice_Arm();late();test('恢复后旧代onPlay不能放行',()=>assert.equal(api.FeedVoice_Position(),-1));
media.emit();test('恢复当前代onPlay不重置位置',()=>assert.equal(api.FeedVoice_Position(),4.2));
media.ended=true;test('实际结束不会伪造播放',()=>assert.equal(api.FeedVoice_Position(),-1));
api.FeedVoice_Release();test('释放恢复原方法并移除监听',()=>{assert.equal(clip.createSourceNode,original);assert.equal(media.listeners.size,0);assert.equal(api.FeedVoice_Position(),-1);});
api.FeedVoice_Remember();ctx.WEBAudio.audioInstances[3]={getLength:()=>11*44100,createSourceNode:()=>({isStopped:false,estimatePlaybackPosition:()=>ctx.WEBAudio.audioContext.currentTime})};
assert.equal(api.FeedVoice_Bind(11),1);ctx.WEBAudio.audioInstances[3].createSourceNode();
test('Buffer上下文未实际推进时冻结',()=>assert.equal(api.FeedVoice_Position(),-1));ctx.WEBAudio.audioContext.currentTime=.2;
test('Buffer实际推进不依赖state字符串',()=>assert.equal(api.FeedVoice_Position(),.2));
api.FeedVoice_Release();
const reportDirectory=process.argv[2]||'.artifacts/FeedAudioTests';
fs.mkdirSync(reportDirectory,{recursive:true});
fs.writeFileSync(path.join(reportDirectory,'browser-bridge-tests.json'),JSON.stringify({passed:true,count:checks.length,scope:'浏览器目标音源与播放位置接口模拟',checks},null,2));console.log(`PASS ${checks.length}/${checks.length}`);
